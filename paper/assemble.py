"""Assemble the manuscript: paper/build/main.tex from the hand-written sections and the floats.

Every %%FLOAT{label} marker in a section is replaced by the float of that label. Tables that make_tables.py writes
(paper/tables/) are used as generated; every other float (figure environments, tables without data) comes from
paper/manuscript/floats/. The figures produced by make_figures.py are copied into the build folder under the names
the manuscript uses (Fig1.pdf and so on), together with the class files and the bibliography.

Also writes paper/build/supplement.tex from paper/supplement/supplement.tex and the generated supplementary tables.

Usage: python paper/assemble.py   (then compile main.tex and supplement.tex in paper/build with pdflatex and bibtex)
"""
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import paths  # noqa: E402

M = paths.MANUSCRIPT
SECTIONS = ['s1_introduction', 's2_s3', 's4', 's5', 's6_s7']
# manuscript figure name -> file written by make_figures.py
FIGURES = {'Fig1': 'fig_framework', 'Fig2': 'fig_pertype_real', 'Fig3': 'fig_hits_vs_types', 'Fig4': 'fig_budget_public',
           'Fig5': 'fig_public_types', 'Fig6': 'fig_sweep', 'FigC1': 'fig_bootstrap'}


def generated_floats():
    """label -> text of every table environment that make_tables.py wrote to paper/tables/."""
    out = {}
    for f in sorted(paths.TABLES.glob('tab_*.tex')):
        for m in re.finditer(r'\\begin\{table\}.*?\\end\{table\}', f.read_text(encoding='utf-8'), re.S):
            lab = re.search(r'\\label\{([^}]*)\}', m.group(0))
            if lab:
                out[lab.group(1)] = m.group(0)
    return out


def float_text(label, generated):
    if label in generated:
        return generated[label]
    f = M / 'floats' / (label.replace(':', '_') + '.tex')
    if not f.exists():
        raise FileNotFoundError(f'float {label}: neither generated by make_tables.py nor in {f}')
    return f.read_text(encoding='utf-8').strip()


def fill(text, generated, used):
    def rep(m):
        used.append(m.group(1))
        return float_text(m.group(1), generated)
    return re.sub(r'%%FLOAT\{([^}]*)\}', rep, text)


def generated_supplement_floats():
    out = {}
    for f in sorted(paths.SUP_TABLES.glob('tabS_*.tex')):
        for m in re.finditer(r'\\begin\{table\}.*?\\end\{table\}', f.read_text(encoding='utf-8'), re.S):
            out[re.search(r'\\label\{([^}]*)\}', m.group(0)).group(1)] = m.group(0)
    return out


def supplement():
    """paper/build/supplement.tex: the supplement text with the tables that make_tables.py generates."""
    gen = generated_supplement_floats()

    def rep(m):
        if m.group(1) not in gen:
            raise KeyError(f'supplementary table {m.group(1)} is not generated by make_tables.py')
        return gen[m.group(1)].strip()
    src = (paths.SUPPLEMENT / 'supplement.tex').read_text(encoding='utf-8')
    (paths.BUILD / 'supplement.tex').write_text(re.sub(r'%%FLOAT\{([^}]*)\}', rep, src), encoding='utf-8')
    print('supplement: tables', len(re.findall(r'%%FLOAT', src)))


def main():
    generated = generated_floats()
    used = []
    front = (M / 'sections' / 'front.tex').read_text(encoding='utf-8')
    abstract = front.split('%% HIGHLIGHTS')[0].strip()
    hl = [l.strip() for l in front.split('%% HIGHLIGHTS')[1].split('%% KEYWORDS')[0].strip().splitlines()]
    kw = [k.strip() for k in front.split('%% KEYWORDS')[1].strip().split(',')]
    fm = ('\\begin{abstract}\n' + abstract + '\n\\end{abstract}\n\n\\begin{highlights}\n'
          + '\n'.join('\\item ' + h for h in hl) + '\n\\end{highlights}\n\n\\begin{keyword}\n'
          + ' \\sep '.join(kw) + '\n\\end{keyword}\n\n\\end{frontmatter}\n\n')
    body = ''
    for s in SECTIONS:
        body += fill((M / 'sections' / f'{s}.tex').read_text(encoding='utf-8'), generated, used).rstrip() + '\n\n'
    app = fill((M / 'sections' / 'appendix.tex').read_text(encoding='utf-8'), generated, used)
    decl = (M / 'declarations.tex').read_text(encoding='utf-8')
    assert decl.count('%%APPENDIX\n') == 1
    decl = decl.replace('%%APPENDIX\n', app + '\n', 1)
    pre = (M / 'preamble.tex').read_text(encoding='utf-8')
    paths.BUILD.mkdir(parents=True, exist_ok=True)
    (paths.BUILD / 'main.tex').write_text(pre + fm + body + decl, encoding='utf-8')
    for f in ('elsarticle.cls', 'elsarticle-harv.bst', 'refs.bib'):
        shutil.copy(M / f, paths.BUILD / f)
    for name, src in FIGURES.items():
        for ext in ('pdf', 'eps'):
            shutil.copy(paths.FIGURES / f'{src}.{ext}', paths.BUILD / f'{name}.{ext}')
    supplement()
    gen_used = [u for u in used if u in generated]
    print('floats:', len(used), '(generated by make_tables.py:', ', '.join(gen_used) or 'none', ')')
    word_count(body, abstract)


def word_count(body, abstract):
    """Words per section (detex, if installed), without floats and equations."""
    if not shutil.which('detex'):
        return
    b = re.sub(r'\\begin\{(figure|table)\}.*?\\end\{\1\}', '', body, flags=re.S)
    b = re.sub(r'\\begin\{equation\}.*?\\end\{equation\}', '', b, flags=re.S)
    tot = 0
    for p in re.split(r'(?=\\section\{)', b):
        if not p.strip() or '\\section{' not in p:
            continue
        tf = os.path.join(tempfile.gettempdir(), 'assemble_wc.tex')
        open(tf, 'w', encoding='utf-8').write(p)
        w = len(subprocess.run(['detex', tf], capture_output=True, text=True).stdout.split()); tot += w
        print(re.search(r'section\{([^}]*)', p).group(1)[:38].ljust(38), w)
    print('TOTAL', tot)
    print('abstract words', len(re.sub(r'\$[^$]*\$', 'X', abstract).split()))


if __name__ == '__main__':
    main()
